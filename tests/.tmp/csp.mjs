import { chromium, devices } from 'playwright';
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['Pixel 7'] });
const page = await ctx.newPage();
const problems = [];
page.on('console', (m) => { if (m.type() === 'error' || /Content Security Policy/i.test(m.text())) problems.push('console: ' + m.text()); });
page.on('pageerror', (e) => problems.push('pageerror: ' + e.message));
await page.addInitScript(() => document.addEventListener('securitypolicyviolation', (e) => console.error('CSP violation ' + e.violatedDirective + ' ' + e.blockedURI)));
await page.goto('http://localhost:5200/');
await page.waitForSelector('.home');
await page.click('.sample-btn');
await page.waitForSelector('.doc .page canvas', { timeout: 30000 });
await page.waitForTimeout(1500);
const ok = await page.evaluate(() => document.fonts.size);
await page.click('[aria-label="편집하기"]').catch(() => {});
await page.waitForTimeout(500);
await page.click('.qb[aria-label="입력 도구"]').catch((e) => problems.push('no insert tool ' + e.message));
await page.click('.tile[aria-label="수식"]').catch((e) => problems.push('no eq ' + e.message));
await page.waitForTimeout(800);
const eqImg = await page.$('.equation-preview img');
await page.screenshot({ path: process.argv[2] });
console.log(JSON.stringify({ fonts: ok, eqPreview: !!eqImg, problems }, null, 1));
await browser.close();
